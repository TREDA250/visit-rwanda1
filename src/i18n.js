const locale = ref(localStorage.getItem('app-locale') || 'en')
if (!messages[locale.value]) {
  locale.value = 'en'
}

function setLocale(value) {
  if (messages[value]) {
    locale.value = value
    localStorage.setItem('app-locale', value)
  }
}

function translate(key) {
  const keys = key.split('.')
  let current = messages[locale.value]
  for (const part of keys) {
    if (!current || typeof current !== 'object') {
      return key
    }
    current = current[part]
  }
  return current ?? key
}

export function useI18n() {
  return {
    locale,
    setLocale,
    t: translate,
    messages,
  }
}

export default {
  install(app) {
    app.provide('i18n', useI18n())
    app.config.globalProperties.$t = translate
  },
}
